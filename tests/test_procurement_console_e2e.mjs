import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=process.env.STUDIO_BASE||'http://127.0.0.1:3031';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const ctx=await browser.newContext({viewport:{width:1540,height:950}});
 const page=await ctx.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',req=>{if(!req.url().startsWith(base+'/')&&!req.url().startsWith('data:'))errors.push('Unapproved external request: '+req.url());});
 await page.goto(base+'/admin/index.html?section=overview',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'종합 관제센터'}).first().waitFor({timeout:20000});
 assert.equal(await page.locator('#side-menu .nav').count(),11);
 await page.locator('[data-page="opportunities"]').first().click();
 assert.match(await page.locator('#page-title').innerText(),/사업기회/);
 assert.equal(await page.locator('.matrix .panel').count(),3);
 await page.locator('[data-page="tests"]').first().click();
 assert.equal(await page.locator('#market-select option').count(),3);
 assert.equal(await page.locator('.panel:has-text("S01~S10") .item').count(),10);
 await page.locator('[data-action="run-all"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('8/8 노드')&&document.body.innerText.includes('HOLD_OFFICIAL_EVIDENCE'),{timeout:30000});
 assert.match(await page.locator('#content').innerText(),/실제 Python/);
 await page.locator('[data-action="inspect-node"][data-node="a01-03"]').click();
 assert.match(await page.locator('#content').innerText(),/노드 INPUT/);
 await page.locator('[data-page="audit"]').first().click();
 await page.locator('[data-action="load-run"]').first().click();
 await page.waitForFunction(()=>document.body.innerText.includes('선택한 실행의 노드별 저장 기록')&&document.body.innerText.includes('a01-08'),{timeout:20000});
 await page.locator('[data-page="tests"]').first().click();
 await page.selectOption('#market-select','private_dev');
 await page.locator('[data-action="run-all"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('7/7 노드')&&document.body.innerText.includes('REVIEW_FOR_CLIENT_PROPOSAL'),{timeout:30000});
 await page.selectOption('#market-select','staffing');
 await page.locator('[data-action="run-all"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('7/7 노드')&&document.body.innerText.includes('HOLD_LEGAL_AND_REAL_STAFF_CHECK'),{timeout:30000});
 await page.locator('[data-page="features"]').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('#content tbody tr').length===104,{timeout:15000});
 assert.equal(await page.locator('#content tbody tr').count(),104);
 await page.locator('#feature-filter').fill('33');
 assert(await page.locator('#content tbody tr').count()>0);
 await page.locator('[data-page="infra"]').first().click();
 assert.match(await page.locator('#content').innerText(),/node_runs/);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-page="audit"]').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('[data-action="load-run"]').length>=3,{timeout:20000});
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PROCUREMENT_FULL_ADMIN_CHROME_11_PAGES_3_MARKET_22_NODE_RUNS_SQLITE_AUDIT_104_FEATURES_PASS');
 await ctx.close();
}finally{await browser.close();}
