import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {simulateAllContracts} from '../n8n/studio-bridge/mock-104-contracts.mjs';
const manifest=JSON.parse(await readFile(new URL('../n8n/operational_manifest.json',import.meta.url)));
const first=simulateAllContracts(manifest), second=simulateAllContracts(manifest);
assert.deepEqual(first,second,'same fixtures must be deterministic');
assert.equal(first.counts.blocks,43);
assert.equal(first.counts.features,104);
assert.equal(first.counts.mockedPass,104);
assert.equal(first.actualJobExecuted,false);
assert.equal(first.officialEvidenceVerified,false);
assert.equal(first.bidSubmitted,false);
assert.equal(first.blocks.filter(x=>x.status==='MOCK_PASS').length,43);
assert.deepEqual(first.featureCoverage.map(x=>x.number),Array.from({length:104},(_,i)=>i+1));
assert(first.blocks.every(x=>x.input.source==='synthetic_fixture'&&x.output.fixtureValue.startsWith('MOCK_')));
const blocked=simulateAllContracts(manifest,{injections:{H05:{fail:true}}});
assert.equal(blocked.status,'HOLD');
assert(blocked.held.includes('H05'));
assert(blocked.featureCoverage.some(x=>x.status==='MOCK_HOLD'));
assert.throws(()=>simulateAllContracts(manifest,{caseId:'R26BK01787028'}),/DEMO_ONLY/);
